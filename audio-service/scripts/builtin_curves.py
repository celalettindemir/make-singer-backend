"""Generate services/vocal_curves.py from reference vocal stems.

Usage: python scripts/builtin_curves.py OUT.py FILE[:m|f] ...

An explicit :m / :f label wins; an unlabelled file falls back to the pitch
median (< 165 Hz is male). Each file's LTAS is shifted so its 500-1500 Hz
median is 0, then the files of one gender are averaged and re-centred.
"""

import datetime
import sys
from pathlib import Path

import numpy as np
from pydub import AudioSegment
from scipy import signal

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from services.guide import track_pitch
from services.vocal_chain import BANDS_HZ, RATE, ltas_db

POINTS_HZ = (250, 500, 1000, 2000, 3000, 5000, 8000, 12000)
MALE_BELOW_HZ = 165.0
CENTER = (BANDS_HZ >= 500) & (BANDS_HZ <= 1500)


def load(path: str) -> np.ndarray:
    seg = AudioSegment.from_file(path).set_channels(1).set_frame_rate(RATE)
    return np.array(seg.get_array_of_samples(), dtype=np.float64) / float(
        1 << (8 * seg.sample_width - 1)
    )


def centered(curve: np.ndarray) -> np.ndarray:
    return curve - np.median(curve[CENTER])


def gender_of(x44: np.ndarray) -> str:
    x16 = signal.resample_poly(x44, 160, 441)
    midi = track_pitch(x16, 16000, "m")
    voiced = midi[~np.isnan(midi)]
    if len(voiced) == 0:
        raise SystemExit("no voiced frames, give an explicit :m or :f label")
    hz = 440.0 * 2.0 ** ((float(np.median(voiced)) - 69.0) / 12.0)
    return "m" if hz < MALE_BELOW_HZ else "f"


def fmt(curve: np.ndarray) -> str:
    return "\n".join(f"            {round(float(v), 2)}," for v in curve)


def main(argv: list[str]) -> None:
    out, files = argv[0], argv[1:]
    groups: dict[str, list[np.ndarray]] = {"m": [], "f": []}
    for spec in files:
        path, _, label = spec.rpartition(":")
        if label not in ("m", "f"):
            path, label = spec, ""
        x = load(path)
        g = label or gender_of(x)
        groups[g].append(centered(ltas_db(x, RATE)))
        print(f"{Path(path).name}: {g}{'' if label else ' (by pitch)'}")
    if not groups["m"] or not groups["f"]:
        raise SystemExit("need at least one male and one female source")

    curves = {
        "builtin-male": np.round(centered(np.mean(groups["m"], axis=0)), 2),
        "builtin-female": np.round(centered(np.mean(groups["f"], axis=0)), 2),
    }
    nm, nf = len(groups["m"]), len(groups["f"])
    lines = [
        '"""Built-in tone reference curves (27 third-octave bands, dB, 500-1500 Hz median 0).',
        "",
        "Generated by scripts/builtin_curves.py - do not edit.",
        f"Sources: male {nm}, female {nf} Suno vocal stems, generated {datetime.datetime.now(tz=datetime.UTC).date()}.",
        f"The male curve has fewer than the spec's 3 sources because only {nm} clearly",
        "male Suno vocal stems exist.",
        '"""',
        "",
        "import numpy as np",
        "",
        "BUILTIN_LTAS = {",
    ]
    for name, c in curves.items():
        lines.append(f'    "{name}": np.array(')
        lines.append("        [")
        lines.append(fmt(c).replace("            ", "            "))
        lines.append("        ]")
        lines.append("    ),")
    lines.append("}")
    Path(out).write_text("\n".join(lines) + "\n")
    for name, c in curves.items():
        pts = [
            round(float(np.interp(np.log(h), np.log(BANDS_HZ), c)), 1)
            for h in POINTS_HZ
        ]
        print(name, dict(zip(POINTS_HZ, pts)))


if __name__ == "__main__":
    main(sys.argv[1:])
